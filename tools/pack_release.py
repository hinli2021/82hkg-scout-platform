#!/usr/bin/env python3
"""Pack the platform into ONE zip you can keep: deliverables/82hkg-platform-<date>.zip

What goes in:
  · every file needed to run or redeploy the app (app.py, scout/, templates/,
    static/, content/, tools/, tests/, requirements.txt, vercel.json, api/)
  · the documents, including the compiled ALL-DOCS.md and the screenshots
  · the original artwork the leader uploaded (uploads/)
  · a MANIFEST.txt listing every member with its size

What stays out (and why):
  · .git — the full history already lives on GitHub
  · demo-preview.html / bridge-preview.html / login-preview.html /
    welcome-preview.html — regenerated by tools/offline_demo.py and
    tools/bridge_preview.py in a minute; they are 15 MB of the pack on their own
  · data/db runtime files and caches — they change on every visit

    cd scout-platform-py && python3 tools/pack_release.py
"""
from __future__ import annotations

import datetime
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT.parent / "deliverables"

SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
             "node_modules", "data/uploads"}
SKIP_FILES = {"demo-preview.html", "bridge-preview.html", "login-preview.html",
              "welcome-preview.html", "ALL-DOCS.zip"}
# runtime state: kept out so a restore never overwrites a live Sheet-backed store
SKIP_PREFIXES = ("data/db/",)


def included(rel: pathlib.Path) -> bool:
    text = rel.as_posix()
    if any(part in SKIP_DIRS for part in rel.parts):
        return False
    if rel.name in SKIP_FILES:
        return False
    if text.startswith(SKIP_PREFIXES):
        return False
    return True


def main() -> None:
    stamp = datetime.date.today().isoformat()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    target = OUT_DIR / f"82hkg-platform-{stamp}.zip"

    rows: list[tuple[str, int]] = []
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        base = ROOT.parent
        for path in sorted(base.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(base)
            if rel.parts[:1] == ("scout-platform-py",):
                inner = pathlib.Path(*rel.parts[1:])
            elif rel.parts[:1] in (("uploads",), ("scout-badge-platform",)):
                inner = rel
            else:
                continue
            if not included(inner):
                continue
            zf.write(path, arcname=rel.as_posix())
            rows.append((rel.as_posix(), path.stat().st_size))

        manifest = [f"港島第八十二旅童軍團 · 平台打包 {stamp}",
                    "82nd Hong Kong Group — Scout Platform release pack", "",
                    "解壓後：scout-platform-py/ 是平台，uploads/ 是你上載的原稿。",
                    "Unzip, then read scout-platform-py/docs/ALL-DOCS.md first.", "",
                    "不含（可重新產生）：.git、離線示範 HTML、data/db 執行時資料。",
                    "Not included: git history, the offline demo HTML files, runtime data.", "",
                    f"{'檔案 file':<58} {'bytes':>10}", "-" * 70]
        for name, size in rows:
            manifest.append(f"{name:<58} {size:>10}")
        manifest.append("-" * 70)
        manifest.append(f"{len(rows)} files, {sum(s for _, s in rows)/1048576:.1f} MB uncompressed")
        zf.writestr("MANIFEST.txt", "\n".join(manifest) + "\n")

    total = target.stat().st_size
    print(f"packed {len(rows)} files → {target} ({total/1048576:.1f} MB)")


if __name__ == "__main__":
    main()
